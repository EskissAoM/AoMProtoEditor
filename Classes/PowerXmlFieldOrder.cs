    private static readonly string[] CommonGroupNames = ["Range Indicator", "Range Indicator Proto", "Radius", "Power Player Relation", "Attack target", "Notification", "Minimap Notification", "Active Power Visibility", "Camera Shake", "Terrain Rumbling", "Sound set", "DualPowerMinDistance", "Power Blocker", "Reveal LOS", "Lighting", "Accuracy", "Ally Damage Ratio", "Reset Ability Charge for", "Plays battle Music"];
    private static readonly IReadOnlyDictionary<string, IReadOnlyDictionary<string, int>> TypeRanks =
        PowerSchemaRegistry.EditorPowerTypes.Append("").ToDictionary(type => type, BuildRanks, StringComparer.OrdinalIgnoreCase);

    internal static string[] GetGroupTags(string name) => Groups[name];
    internal static IEnumerable<string> GroupNames => Groups.Keys;
    internal static IReadOnlyDictionary<string, int> GetRanks(string? type)
        => TypeRanks.TryGetValue(type ?? "", out var ranks) ? ranks : TypeRanks[""];

    internal static bool IsPowerEntry(XElement entry)
        => entry.Name.NamespaceName.Length == 0 && entry.Name.LocalName.Equals("power", StringComparison.OrdinalIgnoreCase) &&
           (string.IsNullOrWhiteSpace((string?)entry.Attribute("type")) || PowerCatalog.IsModCatalogPower(entry));

    private static IReadOnlyDictionary<string, int> BuildRanks(string type)
    {
        var ranks = new Dictionary<string, int>(StringComparer.OrdinalIgnoreCase);
        void Fields(IEnumerable<string> tags)
        {
            foreach (var tag in tags)
                if (!ranks.ContainsKey(tag)) ranks.Add(tag, ranks.Count);
        }
        Fields(["displaynameid", "rolloverid", "activepowerrolloverid", "icon",
            "activetime", "activetimeontarget", "builduptime", "shutdowntime", "shutdownfadetime",
            "cost", "repeatcost", "limitglobal", "limitplayer", "singleactivation", "exclusive", "exclusiveerrormsgid",
            "placement", "abstractplacementtargettype", "explicitlyrestrictedplacementtargettype", "placementrestriction"]);
        foreach (var group in CommonGroupNames) Fields(GetGroupTags(group));
        foreach (var group in PowerSchemaRegistry.GetSpecificGroups(type)) Fields(GetGroupTags(group));
        // Non-default specific groups remain available in the form in declaration order.
        foreach (var group in Groups.Keys.Except(CommonGroupNames, StringComparer.OrdinalIgnoreCase)) Fields(GetGroupTags(group));
        return ranks;
    }

    internal static void NormalizeForEditor(XElement entry)
    {
        if (IsPowerEntry(entry)) EditorXmlOrderPolicy.Normalize(entry, GetRanks((string?)entry.Attribute("type")));
    }

    internal static int FindInsertionIndex(IReadOnlyList<XNode> nodes, XElement entry, XElement field)
        => IsPowerEntry(entry) ? EditorXmlOrderPolicy.FindNewFieldInsertionIndex(nodes, field, GetRanks((string?)entry.Attribute("type"))) : -1;
}
